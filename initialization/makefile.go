package initialization

import (
	"log/slog"
	"os"
	"path/filepath"
)

// MakefileName is the Makefile `sal init` writes into a project.
const MakefileName = "Makefile"

// projectMakefile is the Makefile a project starts with. It documents the
// sal commands a project runs and the terraform ones that deploy it rather
// than being a build system: every target is one command, and nothing needs
// make to run. The tabs are what make requires, so this is not indented
// with spaces anywhere.
const projectMakefile = `# Generated by sal init. The commands this SAL project runs, so that
# ` + "`make <target>`" + ` documents them; each target is one command, and none needs
# make. ` + "`make help`" + ` lists them.
#
# SOURCES are the RDF files or directories sal validates and builds; empty
# means the whole project. BUCKET is where sal upload copies .sal/data: the
# bucket terraform created, or name one with BUCKET=gs://my-bucket/.
SOURCES ?=
TF_DIR ?= terraform
BUCKET ?= $(shell terraform -chdir=$(TF_DIR) output -raw bucket_url 2>/dev/null)

.PHONY: help validate build run construct query sparql serve clean iac plan apply destroy upload

validate: ## check every RDF source against its vocabularies; commits nothing
	sal validate $(SOURCES)

build: ## validate, run SAL module tasks and CONSTRUCT queries, and commit the new triples to .sal/data
	sal build $(SOURCES)

query: ## SQL shell over the built triples table
	sal query

serve: ## SPARQL endpoint and web UI at http://localhost:8080
	sal serve --with-ui

plan: $(TF_DIR)/.terraform ## show what apply would change on Google Cloud
	terraform -chdir=$(TF_DIR) plan

apply: $(TF_DIR)/.terraform ## create or update the bucket and the Cloud Run service
	terraform -chdir=$(TF_DIR) apply

destroy: $(TF_DIR)/.terraform ## remove the Cloud Run service and the bucket
	terraform -chdir=$(TF_DIR) destroy

upload: ## copy .sal/data to the bucket, after a build
	@test -n "$(BUCKET)" || { echo "no bucket: run make apply first, or BUCKET=gs://my-bucket/ make upload"; exit 1; }
	sal upload --bucket $(BUCKET)
`

// writeMakefile writes the project Makefile, leaving one the project already
// has alone, since it is the project's own file once it exists.
func writeMakefile(dir string) error {
	path := filepath.Join(dir, MakefileName)
	if _, err := os.Stat(path); err == nil {
		slog.Warn(MakefileName + " already exists; leaving it unchanged")
		return nil
	} else if !os.IsNotExist(err) {
		return err
	}
	if err := os.WriteFile(path, []byte(projectMakefile), 0644); err != nil {
		return err
	}
	slog.Info("created " + MakefileName)
	return nil
}
