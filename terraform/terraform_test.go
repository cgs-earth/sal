package terraform

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

func readGenerated(t *testing.T, dir string, name string) string {
	t.Helper()
	content, err := os.ReadFile(filepath.Join(dir, name))
	require.NoError(t, err)
	return string(content)
}

func TestGenerateWritesTheConfiguration(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "terraform")

	written, err := Generate(dir, Options{Name: "My Data Product", Project: "cgs-sandbox"})
	require.NoError(t, err)
	require.Equal(t, []string{
		filepath.Join(dir, "main.tf"),
		filepath.Join(dir, "variables.tf"),
		filepath.Join(dir, "outputs.tf"),
		filepath.Join(dir, "terraform.tfvars"),
		filepath.Join(dir, ".gitignore"),
		filepath.Join(dir, "README.md"),
	}, written)

	main := readGenerated(t, dir, "main.tf")
	require.Contains(t, main, `resource "google_storage_bucket" "data"`)
	require.Contains(t, main, `resource "google_cloud_run_v2_service" "serve"`)
	require.Contains(t, main, `execution_environment            = "EXECUTION_ENVIRONMENT_GEN2"`, "a Cloud Storage volume needs the second generation environment")
	require.Contains(t, main, `args = concat(["serve", "--data", local.mount_path], var.with_ui ? ["--with-ui"] : [])`)
	require.Contains(t, main, `mount_path = "/mnt/sal"`)
	require.Contains(t, main, `read_only     = true`)
	require.Contains(t, main, `role   = "roles/storage.objectViewer"`)
	require.Contains(t, main, `deletion_protection = false`, "terraform destroy must be able to remove the service")
	require.Contains(t, main, `cpu_idle          = true`)

	variables := readGenerated(t, dir, "variables.tf")
	require.Contains(t, variables, `default     = "my-data-product"`, "the name is the repository name as a label")
	require.Contains(t, variables, `default     = "us-central1"`)
	require.Contains(t, variables, `default     = "ghcr.io/cgs-earth/sal:latest"`)
	require.Contains(t, variables, "default     = 0\n", "no instance is kept warm by default")
	require.Contains(t, variables, `default     = "2Gi"`)
	require.Contains(t, variables, `default     = ["metadata-cache-ttl-secs=300"]`)
	require.Contains(t, variables, "variable \"with_ui\" {\n  description = \"Whether sal serve also serves its browser UI.")

	require.Equal(t, "# Generated by sal terraform. Values for the variables in variables.tf; every\n# other variable has a default there.\nproject = \"cgs-sandbox\"\n# region = \"us-central1\"\n# public = true\n# with_ui = false\n", readGenerated(t, dir, "terraform.tfvars"))
	require.Contains(t, readGenerated(t, dir, "outputs.tf"), `value       = "gs://${google_storage_bucket.data.name}/"`)
	require.Contains(t, readGenerated(t, dir, ".gitignore"), "*.tfstate\n")
	require.Contains(t, readGenerated(t, dir, "README.md"), "# Deploying My Data Product on Google Cloud")
}

func TestGenerateLeavesTheProjectToBeFilledInWhenNotGiven(t *testing.T) {
	dir := t.TempDir()
	_, err := Generate(dir, Options{Name: "example", Region: "europe-west1", Image: "ghcr.io/me/sal:dev"})
	require.NoError(t, err)

	require.Contains(t, readGenerated(t, dir, "terraform.tfvars"), "# The Google Cloud project ID to deploy into (required).\nproject = \"\"\n")
	variables := readGenerated(t, dir, "variables.tf")
	require.Contains(t, variables, `default     = "europe-west1"`)
	require.Contains(t, variables, `default     = "ghcr.io/me/sal:dev"`)
	require.Contains(t, variables, "condition     = length(var.project) > 0", "an empty project is refused by terraform with advice rather than by the API")
}

func TestGenerateRefusesToReplaceFilesWithoutForce(t *testing.T) {
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "main.tf"), []byte("# mine\n"), 0644))

	_, err := Generate(dir, Options{Name: "example"})
	require.ErrorIs(t, err, ErrExists)
	require.Equal(t, "# mine\n", readGenerated(t, dir, "main.tf"))
	require.NoFileExists(t, filepath.Join(dir, "variables.tf"))

	_, err = Generate(dir, Options{Name: "example", Force: true})
	require.NoError(t, err)
	require.Contains(t, readGenerated(t, dir, "main.tf"), "# Generated by sal terraform.")
}

func TestSlugMakesALabelGoogleCloudAccepts(t *testing.T) {
	require.Equal(t, "my-data-product", Slug("My Data_Product"))
	require.Equal(t, "sal-2024-stations", Slug("2024 stations"))
	require.Equal(t, "sal-", Slug("---"))
	require.Len(t, Slug("a-very-long-repository-name-that-goes-on-and-on-forever"), 30)
}

func TestTerraformCommandRunsInsideAProject(t *testing.T) {
	t.Setenv("HOME", t.TempDir())
	t.Chdir(t.TempDir())
	require.ErrorContains(t, (&TerraformCmd{Dir: DefaultDir}).Run(), "sal terraform runs inside a SAL project")
}
